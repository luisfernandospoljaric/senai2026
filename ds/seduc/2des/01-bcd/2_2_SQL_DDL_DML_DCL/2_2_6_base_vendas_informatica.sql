-- Base didática: Vendas de Produtos de Informática
-- 3 entidades: Produto, Cliente e Venda; 1.000 registros na tabela Venda.
-- Compatível com MySQL 8.0+. Dados fictícios para estudo.
CREATE DATABASE IF NOT EXISTS vendas_informatica CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE vendas_informatica;
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS Venda;
DROP TABLE IF EXISTS Cliente;
DROP TABLE IF EXISTS Produto;
SET FOREIGN_KEY_CHECKS = 1;
CREATE TABLE Produto (
    id_produto INT AUTO_INCREMENT PRIMARY KEY,
    nome_produto VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    marca VARCHAR(60) NOT NULL,
    preco_unitario DECIMAL(10,2) NOT NULL,
    estoque INT NOT NULL DEFAULT 0,
    ativo TINYINT(1) NOT NULL DEFAULT 1,
    data_cadastro DATE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE Cliente (
    id_cliente INT AUTO_INCREMENT PRIMARY KEY,
    nome_cliente VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    cidade VARCHAR(80) NOT NULL,
    estado CHAR(2) NOT NULL,
    data_cadastro DATE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE Venda (
    id_venda INT AUTO_INCREMENT PRIMARY KEY,
    id_produto INT NOT NULL,
    id_cliente INT NOT NULL,
    data_venda DATE NOT NULL,
    quantidade INT NOT NULL,
    preco_unitario_venda DECIMAL(10,2) NOT NULL,
    desconto_percentual DECIMAL(5,2) NOT NULL DEFAULT 0,
    forma_pagamento VARCHAR(30) NOT NULL,
    status_venda VARCHAR(30) NOT NULL,
    CONSTRAINT fk_venda_produto FOREIGN KEY (id_produto) REFERENCES Produto(id_produto),
    CONSTRAINT fk_venda_cliente FOREIGN KEY (id_cliente) REFERENCES Cliente(id_cliente),
    INDEX idx_venda_data (data_venda),
    INDEX idx_venda_cliente (id_cliente),
    INDEX idx_venda_produto (id_produto)
) ENGINE=InnoDB;

